package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"
)

func main() {
	source := flag.String("source", "/usr/share/zoneinfo/tzdata.zi", "IANA tzdata.zi source")
	output := flag.String("output", "user_timezone_aliases.go", "generated Go file")
	expectedVersion := flag.String("version", "", "required IANA tzdb version")
	flag.Parse()

	file, err := os.Open(*source)
	if err != nil {
		fatalf("open tzdb source: %v", err)
	}
	defer file.Close()

	links := make(map[string]string)
	version := ""
	scanner := bufio.NewScanner(file)
	for scanner.Scan() {
		line := scanner.Text()
		if strings.HasPrefix(line, "# version ") {
			fields := strings.Fields(line)
			if len(fields) >= 3 {
				version = strings.TrimSuffix(fields[2], "-rearguard")
			}
			continue
		}
		fields := strings.Fields(line)
		if len(fields) == 3 && fields[0] == "L" {
			links[fields[2]] = fields[1]
		}
	}
	if err := scanner.Err(); err != nil {
		fatalf("read tzdb source: %v", err)
	}
	if version == "" {
		fatalf("tzdb version header not found")
	}
	if *expectedVersion != "" && version != *expectedVersion {
		fatalf("tzdb version is %s, want %s", version, *expectedVersion)
	}
	// Go accepts these canonical-looking UTC spellings, while the service stores
	// one stable representation for all of them.
	links["Etc/GMT"] = "UTC"
	links["Etc/UTC"] = "UTC"

	keys := make([]string, 0, len(links))
	for alias := range links {
		keys = append(keys, alias)
	}
	sort.Strings(keys)

	var generated bytes.Buffer
	fmt.Fprintln(&generated, "package admin")
	fmt.Fprintln(&generated)
	fmt.Fprintf(&generated, "// Code generated from IANA tzdb %s (tzdata.zi Link records). DO NOT EDIT.\n", version)
	fmt.Fprintln(&generated, "//go:generate go run ./internal/gentimezonealiases -source /usr/share/zoneinfo/tzdata.zi -output user_timezone_aliases.go -version", version)
	fmt.Fprintln(&generated, "// Alias keys are accepted input; values are canonical storage identifiers.")
	fmt.Fprintln(&generated, "var ianaTimezoneAliases = map[string]string{")
	for _, alias := range keys {
		target, err := resolve(alias, links, make(map[string]bool))
		if err != nil {
			fatalf("resolve %s: %v", alias, err)
		}
		if target == "Etc/GMT" || target == "Etc/UTC" {
			target = "UTC"
		}
		if alias == target {
			continue
		}
		fmt.Fprintf(&generated, "\t%q: %q,\n", alias, target)
	}
	fmt.Fprintln(&generated, "}")

	formatted, err := format.Source(generated.Bytes())
	if err != nil {
		fatalf("format generated source: %v", err)
	}
	if err := os.WriteFile(*output, formatted, 0o644); err != nil {
		fatalf("write generated source: %v", err)
	}
}

func resolve(value string, links map[string]string, visiting map[string]bool) (string, error) {
	if value == "UTC" {
		return "UTC", nil
	}
	target, ok := links[value]
	if !ok {
		return value, nil
	}
	if visiting[value] {
		return "", fmt.Errorf("alias cycle")
	}
	visiting[value] = true
	resolved, err := resolve(target, links, visiting)
	delete(visiting, value)
	return resolved, err
}

func fatalf(format string, args ...any) {
	fmt.Fprintf(os.Stderr, format+"\n", args...)
	os.Exit(1)
}
