// Explicit DSNs opt in. All mutations are confined to a newly created database;
// the database in the DSN is only used to connect to the server.
func userIDIntegrationDatabase(t *testing.T, dialect string) *sql.DB {
	t.Helper()
	env := "GRPC_KIT_USER_ID_POSTGRES_DSN"
	if dialect == DatabaseDriverMysql {
		env = "GRPC_KIT_USER_ID_MYSQL_DSN"
	}
	dsn := os.Getenv(env)
	if dsn == "" {
		t.Skipf("set %s to run isolated user ID integration tests", env)
	}
	name := fmt.Sprintf("user_id_test_%d", time.Now().UnixNano())
	quoted := pq.QuoteIdentifier(name)
	var isolatedDSN string
	if dialect == DatabaseDriverPostgresql {
		u, err := url.Parse(dsn)
		if err != nil {
			t.Fatal("invalid PostgreSQL integration DSN")
		}
		u.Path = "/" + name
		isolatedDSN = u.String()
	} else {
		cfg, err := mysql.ParseDSN(dsn)
		if err != nil {
			t.Fatal("invalid MySQL integration DSN")
		}
		cfg.DBName = ""
		dsn = cfg.FormatDSN()
		cfg.DBName = name
		isolatedDSN = cfg.FormatDSN()
		quoted = "`" + name + "`"
	}
	server, err := sql.Open(dialect, dsn)
	if err != nil {
		t.Fatal("open integration server failed")
	}
	if _, err := server.ExecContext(t.Context(), "CREATE DATABASE "+quoted); err != nil {
		_ = server.Close()
		t.Fatalf("create isolated database: %v", err)
	}
	t.Cleanup(func() {
		ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
		defer cancel()
		if _, err := server.ExecContext(ctx, "DROP DATABASE "+quoted); err != nil {
			t.Errorf("drop isolated database: %v", err)
		}
		_ = server.Close()
	})
	db, err := sql.Open(dialect, isolatedDSN)
	if err != nil {
		t.Fatal("open isolated database failed")
	}
	t.Cleanup(func() { _ = db.Close() })
	return db
}

func TestLionUsersIDIntegration(t *testing.T) {
	for _, dialect := range []string{DatabaseDriverPostgresql, DatabaseDriverMysql} {
		t.Run(dialect, func(t *testing.T) {
			db := userIDIntegrationDatabase(t, dialect)
			ddl := "CREATE TABLE lion_users (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)"
			insert := "INSERT INTO lion_users DEFAULT VALUES"
			if dialect == DatabaseDriverMysql {
				ddl = "CREATE TABLE lion_users (id BIGINT AUTO_INCREMENT PRIMARY KEY) ENGINE=InnoDB"
				insert = "INSERT INTO lion_users () VALUES ()"
			}
			if _, err := db.ExecContext(t.Context(), ddl); err != nil {
				t.Fatal(err)
			}
			c := &LocalConfig{Database: &DatabaseConfig{Driver: dialect}}
			calibrate := func(t *testing.T) {
				t.Helper()
				if err := c.ensureLionUsersIDStart(t.Context(), db); err != nil {
					t.Fatal(err)
				}
			}
			insertID := func(t *testing.T) int64 {
				t.Helper()
				var id int64
				if dialect == DatabaseDriverPostgresql {
					if err := db.QueryRowContext(t.Context(), insert+" RETURNING id").Scan(&id); err != nil {
						t.Fatal(err)
					}
				} else {
					result, err := db.ExecContext(t.Context(), insert)
					if err != nil {
						t.Fatal(err)
					}
					id, err = result.LastInsertId()
					if err != nil {
						t.Fatal(err)
					}
				}
				return id
			}
			t.Run("first-and-repeated-initialization", func(t *testing.T) {
				calibrate(t)
				calibrate(t)
				if id := insertID(t); id != lionUsersIDStart {
					t.Fatalf("first ID=%d, want %d", id, lionUsersIDStart)
				}
				calibrate(t)
				if id := insertID(t); id != lionUsersIDStart+1 {
					t.Fatalf("next ID=%d", id)
				}
			})
			t.Run("deleted-IDs-are-not-reused", func(t *testing.T) {
				if dialect == DatabaseDriverPostgresql {
					if _, err := db.ExecContext(t.Context(), "ALTER SEQUENCE lion_users_id_seq RESTART WITH 200000"); err != nil {
						t.Fatal(err)
					}
				} else if _, err := db.ExecContext(t.Context(), "ALTER TABLE lion_users AUTO_INCREMENT = 200000"); err != nil {
					t.Fatal(err)
				}
				if id := insertID(t); id != 200000 {
					t.Fatalf("allocated ID=%d", id)
				}
				if _, err := db.ExecContext(t.Context(), "DELETE FROM lion_users"); err != nil {
					t.Fatal(err)
				}
				calibrate(t)
				if id := insertID(t); id != 200001 {
					t.Fatalf("reused historical ID=%d", id)
				}
			})
			t.Run("explicit-import-ahead-of-sequence", func(t *testing.T) {
				if _, err := db.ExecContext(t.Context(), "INSERT INTO lion_users (id) VALUES (300000)"); err != nil {
					t.Fatal(err)
				}
				calibrate(t)
				if id := insertID(t); id != 300001 {
					t.Fatalf("ID after imported row=%d", id)
				}
			})
			t.Run("legacy-static-collision-blocks-initialization", func(t *testing.T) {
				id := crypto.Username2UserID("oneops")
				if _, err := db.ExecContext(t.Context(), fmt.Sprintf("INSERT INTO lion_users (id) VALUES (%d)", id)); err != nil {
					t.Fatal(err)
				}
				c.Security = &SecurityConfig{Authentication: &Authentication{HTTPUsers: []*BasicAuth{{Username: "oneops"}}}}
				if err := c.ensureLionUsersIDStart(t.Context(), db); err == nil {
					t.Fatal("accepted legacy/static ID collision")
				}
				c.Security = nil
				// A failed calibration must release all locks, including MySQL's
				// connection-scoped table lock, before the next writer can proceed.
				ctx, cancel := context.WithTimeout(t.Context(), 3*time.Second)
				defer cancel()
				if _, err := db.ExecContext(ctx, fmt.Sprintf("DELETE FROM lion_users WHERE id = %d", id)); err != nil {
					t.Fatal(err)
				}
			})
			t.Run("parallel-writers-and-calibrators", func(t *testing.T) {
				var wg sync.WaitGroup
				errs := make(chan error, 5)
				for worker := range 5 {
					wg.Go(func() {
						for range 30 {
							var err error
							if worker < 2 {
								err = c.ensureLionUsersIDStart(t.Context(), db)
							} else {
								_, err = db.ExecContext(t.Context(), insert)
							}
							if err != nil {
								errs <- err
								return
							}
						}
					})
				}
				wg.Wait()
				close(errs)
				for err := range errs {
					t.Error(err)
				}
			})
			if dialect == DatabaseDriverPostgresql {
				t.Run("renamed-sequence-and-cached-values", func(t *testing.T) {
					if _, err := db.ExecContext(t.Context(), `ALTER SEQUENCE lion_users_id_seq RENAME TO "review identity"`); err != nil {
						t.Fatal(err)
					}
					if _, err := db.ExecContext(t.Context(), `ALTER SEQUENCE "review identity" RESTART WITH 1 CACHE 10`); err != nil {
						t.Fatal(err)
					}
					cached, err := db.Conn(t.Context())
					if err != nil {
						t.Fatal(err)
					}
					defer func() { _ = cached.Close() }()
					var id int64
					if err := cached.QueryRowContext(t.Context(), `SELECT nextval('"review identity"')`).Scan(&id); err != nil {
						t.Fatal(err)
					}
					calibrate(t)
					if err := cached.QueryRowContext(t.Context(), insert+" RETURNING id").Scan(&id); err != nil {
						t.Fatal(err)
					}
					if id < 300002 {
						t.Fatalf("used stale cached ID %d", id)
					}
				})
			}
		})
	}
}

func TestLionUsersBootstrapIDIntegration(t *testing.T) {
	for _, dialect := range []string{DatabaseDriverPostgresql, DatabaseDriverMysql} {
		t.Run(dialect, func(t *testing.T) {
			db := userIDIntegrationDatabase(t, dialect)
			c := &LocalConfig{Database: &DatabaseConfig{Enable: true, Driver: dialect, db: db}}
			client, err := c.getAdminDatabaseLion(t.Context())
			if err != nil {
				t.Fatal(err)
			}
			api := admin.New(admin.WithLionClient(client), admin.WithAESKey([]byte("0123456789abcdef0123456789abcdef")))
			if _, err := api.CreateDatabaseInitialize(t.Context(), &adminv1.CreateDatabaseInitializeRequest{}); err != nil {
				t.Fatal(err)
			}
			var id int64
			if err := db.QueryRowContext(t.Context(), "SELECT MIN(id) FROM lion_users").Scan(&id); err != nil {
				t.Fatal(err)
			}
			if id != lionUsersIDStart {
				t.Fatalf("bootstrap ID=%d, want %d", id, lionUsersIDStart)
			}
			// Exercise the production initialization boundary, not only the
			// calibrator: it must never return a usable client after a collision.
			if _, err := db.ExecContext(t.Context(), fmt.Sprintf("INSERT INTO lion_users (id, username) VALUES (%d, 'legacy-collision')", crypto.Username2UserID("oneops"))); err != nil {
				t.Fatal(err)
			}
			c.Security = &SecurityConfig{Authentication: &Authentication{HTTPUsers: []*BasicAuth{{Username: "oneops"}}}}
			if client, err := c.getAdminDatabaseLion(t.Context()); err == nil || client != nil {
				t.Fatal("returned a database client after a legacy/static collision")
			}
		})
	}
}
